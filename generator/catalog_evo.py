class _Bag:
    def __init__(self) -> None:
        self.left = {"table": 42, "line": 24, "bar": 14}
        self.i = 0
        self.order = ["table", "line", "table", "bar", "line", "table"]

    def take(self) -> str:
        for _ in range(len(self.order) * 4):
            key = self.order[self.i % len(self.order)]
            self.i += 1
            if self.left[key] > 0:
                self.left[key] -= 1
                return key
        return "table"


_BAG = _Bag()


def _f() -> str:
    return _BAG.take()


